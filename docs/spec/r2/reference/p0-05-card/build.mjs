// 把 card-state.mjs + app.js 打成一个普通脚本，让 index.html 用 file:// 双击就能打开。
// 单一真相仍在两个 .mjs 里；这里只做去 import/export 的机械拼接。
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const strip = (src) => src
  .replace(/^import[^;]+;\s*$/gm, '')
  .replace(/^export\s+/gm, '');

const state = strip(readFileSync(join(here, 'card-state.mjs'), 'utf8'));
const app = strip(readFileSync(join(here, 'app.js'), 'utf8'));
const out = `/* generated by build.mjs — do not edit */
(function(){
'use strict';
${state}
${app}
})();
`;
mkdirSync(join(here, 'dist'), { recursive: true });
writeFileSync(join(here, 'dist/prototype.js'), out);
console.log('built dist/prototype.js', out.length, 'bytes');
